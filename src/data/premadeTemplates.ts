interface TemplateConfig {
  id: string;
  title: string;
  categoryTag: 'community' | 'ecommerce' | 'saas' | 'events' | 'newsletter' | 'creative';
  thumbnailUrl: string;
  brand: string;
  brandColor: string;
  pillText: string;
  heroTitle: string;
  heroSubtitle: string;
  heroImg?: string;
  ctaText: string;
  ctaUrl: string;
  ctaColor: string;
  bgColor?: string;
  cardBg?: string;
  accentColor?: string;
  twoCol?: {
    col1Title: string;
    col1Text: string;
    col1Img: string;
    col2Title: string;
    col2Text: string;
    col2Img: string;
  };
  highlightBox?: {
    stat: string;
    label: string;
    bg: string;
    textColor: string;
  };
}

function buildTemplateDocument(cfg: TemplateConfig): EmailDocument {
  const contentBg = cfg.cardBg || '#ffffff';
  const canvasBg = cfg.bgColor || '#f1f5f9';
  const primaryClr = cfg.ctaColor || '#22c55e';

  const stripes: StripeNode[] = [
    createHeaderStripe(cfg.id, cfg.brand, cfg.brandColor, [
      { label: 'Explore', url: '#' },
      { label: 'Featured', url: '#' },
      { label: 'Community', url: '#' },
    ]),
    {
      id: `${cfg.id}-stripe-hero`,
      stripeType: 'content',
      backgroundColor: contentBg,
      padding: { top: 32, right: 30, bottom: 28, left: 30 },
      structures: [
        {
          id: `${cfg.id}-struct-hero`,
          stackOnMobile: true,
          padding: { top: 0, right: 0, bottom: 0, left: 0 },
          columns: [
            {
              id: `${cfg.id}-col-hero`,
              widthPercent: 100,
              padding: { top: 0, right: 0, bottom: 0, left: 0 },
              blocks: [
                {
                  id: `${cfg.id}-blk-pill`,
                  type: 'text',
                  align: 'center',
                  padding: { top: 0, right: 0, bottom: 12, left: 0 },
                  props: {
                    content: `<span style="display:inline-block;padding:5px 14px;background-color:${primaryClr}18;color:${primaryClr};font-weight:700;font-size:11px;border-radius:9999px;letter-spacing:0.8px;text-transform:uppercase;">${cfg.pillText}</span>`,
                  },
                },
                {
                  id: `${cfg.id}-blk-title`,
                  type: 'text',
                  align: 'center',
                  padding: { top: 0, right: 0, bottom: 10, left: 0 },
                  props: {
                    content: `<h1 style="margin:0;font-size:27px;font-weight:800;color:#0f172a;line-height:1.25;letter-spacing:-0.5px;">${cfg.heroTitle}</h1>`,
                  },
                },
                {
                  id: `${cfg.id}-blk-sub`,
                  type: 'text',
                  align: 'center',
                  padding: { top: 0, right: 0, bottom: 20, left: 0 },
                  props: {
                    content: `<p style="margin:0;font-size:14.5px;color:#475569;line-height:1.55;max-width:520px;margin-left:auto;margin-right:auto;">${cfg.heroSubtitle}</p>`,
                  },
                },
                ...(cfg.heroImg
                  ? [
                      {
                        id: `${cfg.id}-blk-img`,
                        type: 'image' as const,
                        align: 'center' as const,
                        padding: { top: 0, right: 0, bottom: 22, left: 0 },
                        props: {
                          src: cfg.heroImg,
                          alt: cfg.heroTitle,
                          imageWidth: 'full' as const,
                        },
                      },
                    ]
                  : []),
                {
                  id: `${cfg.id}-blk-cta`,
                  type: 'button',
                  align: 'center',
                  padding: { top: 4, right: 0, bottom: 10, left: 0 },
                  props: {
                    text: cfg.ctaText,
                    url: cfg.ctaUrl,
                    buttonColor: primaryClr,
                    textColor: '#ffffff',
                    borderRadius: 8,
                    height: 44,
                  },
                },
              ],
            },
          ],
        },
      ],
    },
  ];

  // Optional Highlight Box
  if (cfg.highlightBox) {
    stripes.push({
      id: `${cfg.id}-stripe-box`,
      stripeType: 'content',
      backgroundColor: contentBg,
      padding: { top: 10, right: 30, bottom: 20, left: 30 },
      structures: [
        {
          id: `${cfg.id}-struct-box`,
          stackOnMobile: true,
          padding: { top: 0, right: 0, bottom: 0, left: 0 },
          columns: [
            {
              id: `${cfg.id}-col-box`,
              widthPercent: 100,
              backgroundColor: cfg.highlightBox.bg,
              padding: { top: 20, right: 20, bottom: 20, left: 20 },
              blocks: [
                {
                  id: `${cfg.id}-blk-box-num`,
                  type: 'text',
                  align: 'center',
                  padding: { top: 0, right: 0, bottom: 4, left: 0 },
                  props: {
                    content: `<div style="font-size:32px;font-weight:800;color:${cfg.highlightBox.textColor};line-height:1;">${cfg.highlightBox.stat}</div>`,
                  },
                },
                {
                  id: `${cfg.id}-blk-box-lbl`,
                  type: 'text',
                  align: 'center',
                  padding: { top: 0, right: 0, bottom: 0, left: 0 },
                  props: {
                    content: `<p style="margin:0;font-size:12.5px;font-weight:600;color:${cfg.highlightBox.textColor};text-transform:uppercase;letter-spacing:0.5px;">${cfg.highlightBox.label}</p>`,
                  },
                },
              ],
            },
          ],
        },
      ],
    });
  }

  // Optional Two-Column Section
  if (cfg.twoCol) {
    stripes.push({
      id: `${cfg.id}-stripe-twocol`,
      stripeType: 'content',
      backgroundColor: contentBg,
      padding: { top: 16, right: 30, bottom: 28, left: 30 },
      structures: [
        {
          id: `${cfg.id}-struct-twocol`,
          stackOnMobile: true,
          padding: { top: 0, right: 0, bottom: 0, left: 0 },
          columns: [
            {
              id: `${cfg.id}-col-c1`,
              widthPercent: 50,
              padding: { top: 10, right: 12, bottom: 10, left: 0 },
              blocks: [
                {
                  id: `${cfg.id}-blk-c1-img`,
                  type: 'image',
                  align: 'center',
                  padding: { top: 0, right: 0, bottom: 10, left: 0 },
                  props: {
                    src: cfg.twoCol.col1Img,
                    alt: cfg.twoCol.col1Title,
                    imageWidth: 'full',
                  },
                },
                {
                  id: `${cfg.id}-blk-c1-t`,
                  type: 'text',
                  align: 'left',
                  padding: { top: 0, right: 0, bottom: 6, left: 0 },
                  props: {
                    content: `<h3 style="margin:0;font-size:16px;font-weight:700;color:#0f172a;">${cfg.twoCol.col1Title}</h3>`,
                  },
                },
                {
                  id: `${cfg.id}-blk-c1-d`,
                  type: 'text',
                  align: 'left',
                  padding: { top: 0, right: 0, bottom: 0, left: 0 },
                  props: {
                    content: `<p style="margin:0;font-size:13px;color:#64748b;line-height:1.5;">${cfg.twoCol.col1Text}</p>`,
                  },
                },
              ],
            },
            {
              id: `${cfg.id}-col-c2`,
              widthPercent: 50,
              padding: { top: 10, right: 0, bottom: 10, left: 12 },
              blocks: [
                {
                  id: `${cfg.id}-blk-c2-img`,
                  type: 'image',
                  align: 'center',
                  padding: { top: 0, right: 0, bottom: 10, left: 0 },
                  props: {
                    src: cfg.twoCol.col2Img,
                    alt: cfg.twoCol.col2Title,
                    imageWidth: 'full',
                  },
                },
                {
                  id: `${cfg.id}-blk-c2-t`,
                  type: 'text',
                  align: 'left',
                  padding: { top: 0, right: 0, bottom: 6, left: 0 },
                  props: {
                    content: `<h3 style="margin:0;font-size:16px;font-weight:700;color:#0f172a;">${cfg.twoCol.col2Title}</h3>`,
                  },
                },
                {
                  id: `${cfg.id}-blk-c2-d`,
                  type: 'text',
                  align: 'left',
                  padding: { top: 0, right: 0, bottom: 0, left: 0 },
                  props: {
                    content: `<p style="margin:0;font-size:13px;color:#64748b;line-height:1.5;">${cfg.twoCol.col2Text}</p>`,
                  },
                },
              ],
            },
          ],
        },
      ],
    });
  }

  // Append Footer
  stripes.push(createFooterStripe(cfg.id, cfg.brand));

  return {
    version: '1.0.0',
    settings: {
      title: cfg.title,
      preheader: cfg.heroSubtitle.slice(0, 80),
      contentWidth: 600,
      backgroundColor: canvasBg,
      contentBackgroundColor: contentBg,
      fontFamily: "-apple-system, BlinkMacSystemFont, 'Inter', 'Segoe UI', Roboto, sans-serif",
      primaryColor: primaryClr,
      textColor: '#1e293b',
      linkColor: primaryClr,
      underlineLinks: false,
      responsive: true,
    },
    stripes,
  };
}

