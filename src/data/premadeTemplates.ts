// Helper builder to create standard stripes with rich creative presets
function createHeaderStripe(id: string, brandText: string, logoColor: string, navItems: { label: string; url: string }[]): StripeNode {
  return {
    id: `${id}-header`,
    stripeType: 'header',
    backgroundColor: '#ffffff',
    padding: { top: 16, right: 28, bottom: 16, left: 28 },
    structures: [
      {
        id: `${id}-struct-header`,
        stackOnMobile: true,
        padding: { top: 0, right: 0, bottom: 0, left: 0 },
        columns: [
          {
            id: `${id}-col-brand`,
            widthPercent: 40,
            padding: { top: 0, right: 0, bottom: 0, left: 0 },
            blocks: [
              {
                id: `${id}-blk-logo`,
                type: 'text',
                align: 'left',
                padding: { top: 4, right: 0, bottom: 4, left: 0 },
                props: {
                  content: `<h2 style="margin:0;font-size:19px;font-weight:700;color:${logoColor};letter-spacing:-0.3px;">${brandText}</h2>`,
                },
              },
            ],
          },
          {
            id: `${id}-col-nav`,
            widthPercent: 60,
            padding: { top: 0, right: 0, bottom: 0, left: 0 },
            blocks: [
              {
                id: `${id}-blk-nav`,
                type: 'menu',
                align: 'right',
                padding: { top: 6, right: 0, bottom: 6, left: 0 },
                props: {
                  menuItems: navItems.map((item, idx) => ({ id: `${idx}`, label: item.label, url: item.url })),
                },
              },
            ],
          },
        ],
      },
    ],
  };
}

